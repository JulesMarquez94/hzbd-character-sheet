/**
 * Write src/lib/cardArt.js or src/lib/itemArt.js.
 *
 * Shared by pull-card-art.mjs and pull-item-art.mjs, which used to carry a copy
 * of this text each. They had to stop: the two manifests say the same thing
 * about the same arrangement, and the arrangement is now the one thing in the
 * picture pipeline that is easy to get subtly wrong. One emitter means the two
 * files cannot describe different rules, and means the day commissioned art
 * needs a second shape only one place learns about it.
 *
 * ------------------------------------------------------------------ what it emits
 * Every entry is a `codex:` reference into the private bucket, because every
 * picture in the codex today is AI generated placeholder art. See the header it
 * writes, and src/lib/codexArt.js for the naming law.
 *
 * An entry **without** the prefix is a plain path into public/, served from the
 * edge, which is where commissioned art goes. There is none yet, so this emits
 * nothing of the sort, and the reader (useCodexArt) already handles both.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const HEADER = ({ what, noun, script, run, big, small }) => `/**
 * ${what} art, keyed by ${noun} id.
 *
 * Generated by scripts/${script} — do not edit by hand. Run \`npm run
 * ${run}\` after changing what feeds it, then \`npm run art:push\` to send the
 * pictures themselves.
 *
 * ------------------------------------------------------------------ the bucket
 * Every entry here is a \`codex:\` reference into a **private Supabase bucket**,
 * not a path into public/. The pictures are AI generated placeholder art made
 * for one table, and this repository is public: shipping them inside it meant
 * the art rule decided whether a plate was *drawn* while the file behind it
 * stayed readable by anybody who guessed a path or simply browsed the code.
 *
 * So a reference names an object and useCodexArt signs it at the moment of
 * drawing, which the policy on the bucket has to allow first. The naming law is
 * src/lib/codexArt.js and the policy is the CODEX ART section of
 * supabase/schema.sql.
 *
 * Two cuts, because there are two plates:
 *
 *   .full.webp   ${big}
 *   .thumb.webp  ${small}
 *
 * ------------------------------------------------------------ the other home
 * An entry **without** the \`codex:\` prefix is a plain path into public/ and is
 * served from the edge exactly as everything here used to be. That is where
 * commissioned art goes: it is owned, it is meant to be seen, and it wants a
 * cache rather than a signature. There is none yet. The day there is, that one
 * entry changes shape and nothing that reads this file is touched.
 *
 * ------------------------------------------------------------------ the gate
 * Nothing here decides who *sees* a picture. Codex art is a friend capability
 * (see \`showsArt\` in tiers.js), checked at the moment of drawing in
 * useCodexArt.js, and enforced for real by the bucket's own policy. This file
 * only says what the picture is.
 */
`;

/**
 * @param root      the repository root
 * @param set       'cards' or 'items'
 * @param ids       every id that has a picture, in any order
 * @param the rest  the words that differ between the two files
 */
export function writeArtManifest({ root, set, ids, what, noun, script, run, big, small, thumbFor }) {
  const constName = set === 'cards' ? 'CARD_ART' : 'ITEM_ART';
  const article = set === 'cards' ? 'a card' : 'an item';
  const Article = set === 'cards' ? 'A card' : 'An item';

  const rows = [...ids]
    .sort((a, b) => a.localeCompare(b))
    .map((id) => `  '${id}': 'codex:${set}/${id}.full.webp',`)
    .join('\n');

  const body = `${HEADER({ what, noun, script, run, big, small })}
const ${constName} = {
${rows}
};

/** The art for one ${noun}, or null for ${article} that has none yet. */
export function artFor(id) {
  return ${constName}[id] ?? null;
}

/** The small cut of it, for the ${thumbFor}. */
export function thumbFor(id) {
  const full = ${constName}[id];
  return full ? full.replace(/\\.full\\.webp$/, '.thumb.webp') : null;
}

/**
 * The same list of ${set} with their art attached, for the codex to wrap its
 * own arrays in. ${Article} that has no picture keeps \`art_url: null\` rather than
 * losing the field, so a reader never has to guess whether the absence is
 * missing art or a missing lookup.
 */
export function withArt(${set}) {
  return ${set}.map((${noun}) => ({
    ...${noun},
    art_url: artFor(${noun}.id),
    art_thumb: thumbFor(${noun}.id),
  }));
}
`;

  writeFileSync(path.join(root, 'src/lib', `${set === 'cards' ? 'card' : 'item'}Art.js`), body, 'utf8');
  return ids.length;
}
